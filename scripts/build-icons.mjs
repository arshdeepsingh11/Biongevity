#!/usr/bin/env node
/**
 * Generates src/components/ui/icon-data.ts from @phosphor-icons/core — only the icons listed in
 * src/components/ui/icon-names.ts and only the weights the site renders (regular, bold, fill).
 * The full @phosphor-icons/react package shipped all six weights of every icon (~470 KB of JS).
 * Run: npm run icons
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ASSETS = join(ROOT, "node_modules/@phosphor-icons/core/assets");
const names = readFileSync(join(ROOT, "src/components/ui/icon-names.ts"), "utf8");
const files = [...new Set([...names.matchAll(/:\s*"([a-z0-9-]+)"/g)].map((m) => m[1]))].sort();

const WEIGHTS = [["regular", ""], ["bold", "-bold"], ["fill", "-fill"]];
const paths = (file) => {
  const svg = readFileSync(file, "utf8");
  if (/<(?!\/?(svg|path)\b)\w+/.test(svg)) throw new Error(`Unexpected SVG element in ${file}`);
  return [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
};

const data = {};
for (const f of files) {
  data[f] = WEIGHTS.map(([w, suffix]) => {
    const file = join(ASSETS, w, `${f}${suffix}.svg`);
    if (!existsSync(file)) throw new Error(`Phosphor icon not found: ${w}/${f}${suffix}.svg — check icon-names.ts`);
    return paths(file);
  });
}

const out = `// Generated by scripts/build-icons.mjs from @phosphor-icons/core — do not edit. Run \`npm run icons\`.
/** Phosphor file name → path data for [regular, bold, fill]. viewBox 0 0 256 256. */
export const ICON_DATA: Record<string, [string[], string[], string[]]> = ${JSON.stringify(data)};
`;
writeFileSync(join(ROOT, "src/components/ui/icon-data.ts"), out);
console.log(`✓ icon-data.ts: ${files.length} icons × 3 weights, ${(out.length / 1024).toFixed(0)} KB`);
